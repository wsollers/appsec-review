"""Gradle compiler provenance for the JVM language build.

Gradle compiles Java and Kotlin inside its own JVM through compiler APIs, so the PATH wrappers that
observe Maven's forked javac never run. A run-owned init script closes that gap where it can:

* every `JavaCompile` task (plain Gradle and Android Gradle Plugin alike) is forked through the
  command-line compiler of a run-owned JDK mirror. The mirror links every entry of the task's own
  toolchain JDK except `bin/javac` and `bin/java`, which are instrumented wrappers, so Gradle's
  toolchain probe still sees a complete JDK of the same version and the observed exec is the real
  compiler with Gradle's exact `@argfile`;
* Kotlin JVM compile tasks are asked to compile out of process; when their toolchain is the Gradle
  JVM, the launcher is the mirror's instrumented `java`, so the `K2JVMCompiler` exec is observed;
* every compile and Android dex task also emits a build-tool-declared record (task path,
  configured compiler arguments, sources, destination, toolchain). Declared records are typed
  apart from observed execs and never stand in for one: a compile task that did work without a
  matching observed exec, and every in-process D8/R8 dex task, is a named gap.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
import hashlib
import json
from pathlib import Path
from typing import Any


INIT_SCRIPT_NAME = "appsec-provenance.init.gradle"
TASK_RECORD_SCHEMA = "appsec-review/gradle-task-record/1"
TEMPLATE_PLACEHOLDER = "@APPSEC_REAL_TOOL@"
# Wrapped inside the JDK mirror. Every other JDK entry is a symlink to the real toolchain.
MIRRORED_TOOLS = ("java", "javac")
KOTLIN_COMPILER_MAIN = "org.jetbrains.kotlin.cli.jvm.K2JVMCompiler"
DECLARED_CONFIDENCE = 0.5

# Recipe flags that would hide compilation from observation (a reused daemon keeps a stale
# environment, a cache hit or configuration-cache replay skips the init script's hooks).
_DEFEATING_FLAGS = {"--daemon", "--build-cache", "--configuration-cache"}
_FORCED_FLAGS = ("--no-daemon", "--no-build-cache", "--no-configuration-cache",
                 "-Pkotlin.compiler.execution.strategy=out-of-process")

INIT_SCRIPT = r"""// Generated by appsec-review (appsec-review/gradle-provenance-init/1). Run-owned build
// instrumentation, never target guidance. It changes no task selection: it forks javac through an
// instrumented mirror of the task's own JDK, requests out-of-process Kotlin compilation, and records
// build-tool-declared compile and dex task configuration. Instrumentation failures are recorded,
// never fatal.
import groovy.json.JsonOutput
import java.nio.file.FileVisitResult
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.SimpleFileVisitor
import java.nio.file.attribute.BasicFileAttributes
import java.security.MessageDigest

def appsecRootPath = System.getenv('APPSEC_JVM_INSTRUMENTATION')
if (appsecRootPath) {
  def appsecRoot = new File(appsecRootPath)
  def appsecParent = System.getenv('APPSEC_JVM_PARENT_COMMAND') ?: 'unknown'
  def appsecRecords = new File(appsecRoot, 'gradle-tasks.jsonl')
  def appsecLock = new Object()

  def appsecWrite = { Map record ->
    Map row = new LinkedHashMap(record)
    row.schema = 'appsec-review/gradle-task-record/1'
    row.parent_command_id = appsecParent
    String line = JsonOutput.toJson(row) + '\n'
    synchronized (appsecLock) { appsecRecords.append(line, 'UTF-8') }
  }
  def appsecTry = { Closure action ->
    try { return action.call() } catch (Throwable error) { return [unavailable: error.getClass().name] }
  }
  def appsecPaths = { collection -> collection == null ? [] : collection.files.collect { it.path }.sort() }
  def appsecType = { task -> task.getClass().name.replaceAll(/_Decorated$/, '') }
  def appsecExtends = { task, String name ->
    def type = task.getClass()
    while (type != null) { if (type.name == name) return true; type = type.superclass }
    return false
  }
  def appsecDexTool = { task ->
    def type = task.getClass()
    while (type != null) {
      if (type.name.startsWith('com.android.build.')) {
        String simple = type.simpleName
        if (simple ==~ /^(R8|L8R8).*Task$/) return 'r8'
        if (simple ==~ /^(Dex|D8|L8Dex).*Task$/) return 'd8'
      }
      type = type.superclass
    }
    return null
  }
  def appsecHex = { String value ->
    MessageDigest.getInstance('SHA-256').digest(value.getBytes('UTF-8')).encodeHex().toString()
  }
  def appsecQuote = { String value -> "'" + value.replace("'", "'\\''") + "'" }
  def appsecDelete = { File directory ->
    if (!directory.exists()) return
    Files.walkFileTree(directory.toPath(), new SimpleFileVisitor<Path>() {
      FileVisitResult visitFile(Path file, BasicFileAttributes attributes) {
        Files.delete(file); return FileVisitResult.CONTINUE
      }
      FileVisitResult postVisitDirectory(Path dir, IOException error) {
        Files.delete(dir); return FileVisitResult.CONTINUE
      }
    })
  }
  def appsecMirror = { File realHome ->
    File home = realHome.canonicalFile
    File realBin = new File(home, 'bin')
    if (!new File(realBin, 'javac').canExecute()) throw new GradleException('JDK home has no javac: ' + home)
    File mirror = new File(appsecRoot, 'jdk/' + appsecHex(home.path).substring(0, 16))
    synchronized (appsecLock) {
      if (!new File(mirror, '.complete').isFile()) {
        appsecDelete(mirror)
        File bin = new File(mirror, 'bin')
        bin.mkdirs()
        home.listFiles().sort { it.name }.each { entry ->
          if (entry.name != 'bin') Files.createSymbolicLink(new File(mirror, entry.name).toPath(), entry.toPath())
        }
        realBin.listFiles().sort { it.name }.each { entry ->
          File target = new File(bin, entry.name)
          File template = new File(appsecRoot, 'gradle/' + entry.name + '.template')
          if (template.isFile()) {
            target.setText(template.getText('UTF-8').replace('@APPSEC_REAL_TOOL@', appsecQuote(entry.path)), 'UTF-8')
            target.setExecutable(true, false)
            target.setReadable(true, false)
          } else {
            Files.createSymbolicLink(target.toPath(), entry.toPath())
          }
        }
        new File(mirror, '.complete').setText(home.path, 'UTF-8')
      }
    }
    return mirror
  }

  def appsecJavaRecord = { task, String kind ->
    Map record = [task_path: task.path, task_type: appsecType(task), compiler: 'javac', record_kind: kind]
    record.compiler_args = appsecTry { task.options.allCompilerArgs.collect { it.toString() } }
    record.source_files = appsecTry { appsecPaths(task.source) }
    record.destination_directory = appsecTry { task.destinationDirectory.get().asFile.path }
    record.classpath = appsecTry { appsecPaths(task.classpath) }
    record.annotation_processor_path = appsecTry { appsecPaths(task.options.annotationProcessorPath) }
    record.bootstrap_classpath = appsecTry { appsecPaths(task.options.bootstrapClasspath) }
    record.generated_source_directory = appsecTry { task.options.generatedSourceOutputDirectory.getOrNull()?.asFile?.path }
    record.release = appsecTry { task.options.release.getOrNull() }
    record.source_compatibility = appsecTry { task.sourceCompatibility?.toString() }
    record.target_compatibility = appsecTry { task.targetCompatibility?.toString() }
    record.fork = appsecTry { task.options.fork }
    record.fork_executable = appsecTry { task.options.forkOptions.executable }
    return record
  }
  def appsecKotlinRecord = { task, String kind ->
    Map record = [task_path: task.path, task_type: appsecType(task), compiler: 'kotlinc', record_kind: kind]
    record.compiler_args = appsecTry { task.compilerOptions.freeCompilerArgs.get().collect { it.toString() } }
    record.source_files = appsecTry { appsecPaths(task.hasProperty('sources') ? task.sources : task.source) }
    record.destination_directory = appsecTry { task.destinationDirectory.get().asFile.path }
    record.classpath = appsecTry { appsecPaths(task.libraries) }
    record.jvm_target = appsecTry { task.compilerOptions.jvmTarget.get().target }
    record.module_name = appsecTry { task.compilerOptions.moduleName.getOrNull() }
    record.execution_strategy = appsecTry { task.compilerExecutionStrategy.get().toString() }
    record.toolchain_java_version = appsecTry { task.kotlinJavaToolchain.javaVersion.get().toString() }
    return record
  }
  def appsecCompleted = { task, String compiler ->
    appsecWrite([task_path: task.path, task_type: appsecType(task), compiler: compiler,
                 record_kind: 'completed', did_work: task.didWork])
  }

  def appsecFacts = new java.util.concurrent.ConcurrentHashMap()
  def appsecFactsFor = { task, String compiler ->
    appsecFacts.computeIfAbsent(task.path, { key -> Collections.synchronizedMap(new LinkedHashMap(
      [task_path: task.path, task_type: appsecType(task), compiler: compiler, record_kind: 'configured'])) })
  }

  def appsecReplaceJavaToolchain = { task ->
    // Gradle 8 validates a fork executable against the canonical home of the task's javaCompiler
    // toolchain, so the toolchain itself is replaced, lazily, by the mirror of whatever JDK the
    // task would have used (explicit toolchain, java extension toolchain, or the Gradle JVM).
    Map facts = appsecFactsFor(task, 'javac')
    try {
      def objects = task.project.objects
      def toolchains = task.project.extensions.getByType(org.gradle.jvm.toolchain.JavaToolchainService)
      // Gradle's own fork-executable convention uses this internal spec; its factory parameter is
      // an ObjectFactory in Gradle 8.9 and a PropertyFactory service in later 8.x releases.
      def specType = toolchains.getClass().classLoader.loadClass('org.gradle.jvm.toolchain.internal.SpecificInstallationToolchainSpec')
      def fromJavaHome = specType.methods.find { it.name == 'fromJavaHome' && it.parameterTypes.length == 2 }
      def factory = fromJavaHome.parameterTypes[0].isInstance(objects) ? objects :
          task.project.services.get(fromJavaHome.parameterTypes[0])
      task.javaCompiler.replace { original ->
        original.map { compiler ->
          try {
            File mirror = appsecMirror(compiler.metadata.installationPath.asFile)
            return toolchains.compilerFor(fromJavaHome.invoke(null, factory, mirror)).get()
          } catch (Throwable error) {
            facts.mirror_error = error.getClass().name
            return compiler
          }
        }
      }
      facts.toolchain_replacement = 'mirror'
    } catch (Throwable error) {
      facts.replacement_error = error.getClass().name
    }
  }
  def appsecConfigureJava = { task ->
    Map facts = appsecFactsFor(task, 'javac')
    task.doFirst {
      try {
        def compiler = task.javaCompiler.get()
        File home = compiler.metadata.installationPath.asFile
        File marker = new File(home, '.complete')
        if (home.parentFile?.canonicalFile == new File(appsecRoot, 'jdk').canonicalFile && marker.isFile()) {
          facts.toolchain_home = marker.getText('UTF-8')
          if (task.options.forkOptions.javaHome != null) {
            facts.replaced_fork_java_home = task.options.forkOptions.javaHome.path
            task.options.forkOptions.javaHome = null
          }
          if (task.options.forkOptions.executable) facts.replaced_fork_executable = task.options.forkOptions.executable
          task.options.fork = true
          task.options.forkOptions.executable = compiler.executablePath.asFile.path
          facts.fork_executable = task.options.forkOptions.executable
          facts.observation = 'fork-requested'
        } else {
          facts.toolchain_home = home.path
          facts.observation = 'fork-unavailable'
        }
      } catch (Throwable error) {
        facts.observation = 'fork-unavailable'
        facts.error = error.getClass().name
      }
      appsecWrite(new LinkedHashMap(facts))
      Map record = appsecJavaRecord(task, 'before-compile')
      record.toolchain_home = facts.toolchain_home
      appsecWrite(record)
    }
    task.doLast { appsecCompleted(task, 'javac') }
  }
  def appsecReplaceKotlinLauncher = { task ->
    Map facts = appsecFactsFor(task, 'kotlinc')
    try {
      def strategy = task.getClass().classLoader.loadClass('org.jetbrains.kotlin.gradle.tasks.KotlinCompilerExecutionStrategy')
      task.compilerExecutionStrategy.set(Enum.valueOf(strategy, 'OUT_OF_PROCESS'))
      facts.execution_strategy = 'out-of-process'
    } catch (Throwable error) {
      facts.execution_strategy_error = error.getClass().name
    }
    try {
      // KGP's toolchain follows the java extension toolchain, or the Gradle JVM when none is
      // configured. Only the Gradle JVM case is redirected; reading KGP's own toolchain property
      // here could finalize it.
      def java = task.project.extensions.findByType(org.gradle.api.plugins.JavaPluginExtension)
      def requested = java?.toolchain?.languageVersion?.getOrNull()
      if (requested == null || requested.asInt() == Integer.parseInt(JavaVersion.current().majorVersion)) {
        File mirror = appsecMirror(new File(System.getProperty('java.home')))
        task.kotlinJavaToolchain.jdk.use(mirror, JavaVersion.current())
        facts.launcher_home = mirror.path
        facts.toolchain_home = new File(System.getProperty('java.home')).canonicalPath
        facts.observation = facts.execution_strategy ? 'out-of-process-requested' : 'launcher-instrumented'
      } else {
        facts.observation = 'launcher-not-instrumented'
        facts.reason = 'Kotlin toolchain Java ' + requested + ' differs from the Gradle JVM'
      }
    } catch (Throwable error) {
      facts.observation = 'launcher-not-instrumented'
      facts.error = error.getClass().name
    }
  }
  def appsecConfigureKotlin = { task ->
    Map facts = appsecFactsFor(task, 'kotlinc')
    task.doFirst {
      appsecWrite(new LinkedHashMap(facts))
      appsecWrite(appsecKotlinRecord(task, 'before-compile'))
    }
    task.doLast { appsecCompleted(task, 'kotlinc') }
  }
  def appsecConfigureDex = { task, String tool ->
    task.doFirst {
      appsecWrite([task_path: task.path, task_type: appsecType(task), compiler: tool, record_kind: 'dex-task',
                   output_files: appsecTry { appsecPaths(task.outputs.files) },
                   input_file_count: appsecTry { task.inputs.files.files.size() }])
    }
    task.doLast { appsecCompleted(task, tool) }
  }

  appsecWrite([record_kind: 'session', gradle_version: gradle.gradleVersion,
               gradle_java_home: System.getProperty('java.home'),
               gradle_java_version: System.getProperty('java.version')])
  // After every build script and plugin has configured its tasks, but before the task graph
  // reads (and finalizes) any toolchain, so the replacement wraps the toolchain each task chose.
  gradle.projectsEvaluated {
    gradle.allprojects { project ->
      project.tasks.withType(org.gradle.api.tasks.compile.JavaCompile).configureEach { task ->
        appsecReplaceJavaToolchain(task)
      }
      project.tasks.configureEach { task ->
        if (appsecExtends(task, 'org.jetbrains.kotlin.gradle.tasks.KotlinCompile')) appsecReplaceKotlinLauncher(task)
      }
    }
  }
  gradle.taskGraph.whenReady { graph ->
    graph.allTasks.each { task ->
      if (task instanceof org.gradle.api.tasks.compile.JavaCompile) {
        appsecConfigureJava(task)
      } else if (appsecExtends(task, 'org.jetbrains.kotlin.gradle.tasks.KotlinCompile')) {
        appsecConfigureKotlin(task)
      } else {
        String tool = appsecDexTool(task)
        if (tool != null) appsecConfigureDex(task, tool)
      }
    }
  }
}
"""

INIT_SCRIPT_SHA256 = hashlib.sha256(INIT_SCRIPT.encode("utf-8")).hexdigest()


def write_init_script(root: Path, templates: Mapping[str, str]) -> Path:
    """Write the init script and the mirror wrapper templates under the instrumentation root."""
    directory = root / "gradle"
    directory.mkdir(parents=True, exist_ok=True)
    for tool in MIRRORED_TOOLS:
        template = directory / f"{tool}.template"
        template.write_text(templates[tool], encoding="utf-8", newline="\n")
        template.chmod(0o644)
    script = directory / INIT_SCRIPT_NAME
    script.write_text(INIT_SCRIPT, encoding="utf-8", newline="\n")
    script.chmod(0o644)
    return script


def instrument_argv(argv: Sequence[str], logical_root: str) -> tuple[tuple[str, ...], dict[str, Any]]:
    """Add the provenance init script and the flags that keep compilation observable.

    Validation of the accepted command has already happened; the additions are options only, so
    they never change which tasks run. Removed recipe flags are reported, not hidden.
    """
    kept, removed = [str(argv[0])], []
    for value in argv[1:]:
        if str(value) in _DEFEATING_FLAGS:
            removed.append(str(value))
        else:
            kept.append(str(value))
    added = [flag for flag in _FORCED_FLAGS if flag not in kept]
    script = f"{logical_root}/gradle/{INIT_SCRIPT_NAME}"
    added.extend(("--init-script", script))
    return tuple(kept + added), {"gradle_init_script": {"path": script, "sha256": INIT_SCRIPT_SHA256},
                                 "added_arguments": added, "removed_arguments": removed}


def parse_argfile(text: str) -> list[str]:
    """Tokenize a javac/kotlinc `@argfile`: whitespace separated, quoted, `#` line comments."""
    tokens: list[str] = []
    index, size = 0, len(text)
    escapes = {"n": "\n", "r": "\r", "t": "\t", "f": "\f"}
    while index < size:
        char = text[index]
        if char.isspace():
            index += 1
            continue
        if char == "#":
            while index < size and text[index] not in "\r\n":
                index += 1
            continue
        token: list[str] = []
        while index < size and not text[index].isspace():
            char = text[index]
            if char in "\"'":
                quote, index = char, index + 1
                while index < size and text[index] != quote:
                    if text[index] == "\\" and index + 1 < size:
                        index += 1
                        token.append(escapes.get(text[index], text[index]))
                    else:
                        token.append(text[index])
                    index += 1
                index += 1
            else:
                token.append(char)
                index += 1
        tokens.append("".join(token))
    return tokens


def expanded_argv(argv: Sequence[str], argfiles: Mapping[str, str]) -> list[str]:
    """Replace each `@file` argument whose content was captured at exec time by its tokens."""
    result: list[str] = []
    for value in argv:
        if value.startswith("@") and value[1:] in argfiles:
            result.extend(parse_argfile(argfiles[value[1:]]))
        else:
            result.append(value)
    return result


def read_task_records(path: Path, byte_limit: int, count_limit: int) -> tuple[list[dict[str, Any]], list[str]]:
    if not path.is_file() or path.is_symlink():
        return [], []
    data, gaps = path.read_bytes(), []
    if len(data) > byte_limit:
        data = data[:byte_limit]
        gaps.append("Gradle task provenance records exceeded their configured byte bound")
    records: list[dict[str, Any]] = []
    for line in data.split(b"\n"):
        if not line.strip():
            continue
        if len(records) >= count_limit:
            gaps.append("Gradle task provenance records exceeded their configured count bound")
            break
        try:
            value = json.loads(line.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError):
            gaps.append("Gradle task provenance records contain an invalid record")
            break
        if not isinstance(value, dict) or value.get("schema") != TASK_RECORD_SCHEMA:
            gaps.append("Gradle task provenance records contain an invalid record")
            break
        records.append(value)
    return records, gaps


def _strings(value: Any) -> list[str]:
    return [str(item) for item in value] if isinstance(value, list) else []


def _destination(argv: Sequence[str]) -> str | None:
    for index, value in enumerate(argv):
        if value == "-d" and index + 1 < len(argv):
            return argv[index + 1].rstrip("/") or "/"
    return None


def declared_compilations(records: Sequence[Mapping[str, Any]], observed: Sequence[Mapping[str, Any]],
                          mapped: Any) -> tuple[list[dict[str, Any]], list[str]]:
    """Fold task records into build-tool-declared rows and name every unobserved compilation.

    `observed` rows carry the protected `expanded_argv`; a declared compile task is matched to an
    observed compiler exec only by the same parent command, compiler, and `-d` destination.
    """
    tasks: dict[tuple[str, str], dict[str, Any]] = {}
    gaps: list[str] = []
    for record in records:
        kind, path = record.get("record_kind"), record.get("task_path")
        if kind == "session" or not isinstance(path, str):
            continue
        key = (str(record.get("parent_command_id")), path)
        row = tasks.setdefault(key, {"task_path": path, "parent_command_id": key[0],
                                     "task_type": record.get("task_type"),
                                     "tool": record.get("compiler")})
        if kind == "configured":
            row["instrumentation"] = {name: record.get(name) for name in (
                "observation", "toolchain_replacement", "replacement_error", "mirror_error",
                "toolchain_home", "fork_executable",
                "replaced_fork_java_home", "replaced_fork_executable", "execution_strategy",
                "execution_strategy_error", "launcher_home", "reason", "error") if record.get(name) is not None}
        elif kind in {"before-compile", "dex-task"}:
            row["declared"] = dict(record)
        elif kind == "completed":
            row["did_work"] = record.get("did_work")
    def location(value: str | None) -> str | None:
        # Compare workspace-resolved locations, so a relative `-d` and Gradle's absolute
        # container path name the same directory; unresolvable values compare verbatim.
        if value is None:
            return None
        resolved = mapped([value])
        return str(resolved[0]["workspace_path"]) if resolved else value

    observed_locations = [(item, location(_destination(item.get("expanded_argv") or item.get("argv") or ())))
                          for item in observed]
    rows: list[dict[str, Any]] = []
    for (parent, path), row in sorted(tasks.items(), key=lambda item: item[0]):
        tool = str(row.get("tool"))
        declared = row.get("declared", {})
        if tool in {"d8", "r8"}:
            outputs = _strings(declared.get("output_files"))
            matches: list[int] = []
            if declared:
                gaps.append(f"Android dex task {path} ran {tool.upper()} in-process inside Gradle; "
                            "its invocation was not observed and only build-tool-declared outputs "
                            "are recorded (artifact-transform dexing of external libraries is not recorded)")
            inputs: list[dict[str, Any]] = []
        else:
            destination = declared.get("destination_directory")
            destination = destination.rstrip("/") if isinstance(destination, str) else None
            wanted = location(destination)
            matches = [int(item["ordinal"]) for item, where in observed_locations
                       if item.get("tool") == tool and str(item.get("parent_command_id")) == parent and
                       wanted is not None and where == wanted]
            inputs = mapped(_strings(declared.get("source_files")))
            outputs = [destination] if destination else []
            if declared and row.get("did_work") is not False and not matches:
                gaps.append(f"Gradle task {path} ran {tool} without an observed compiler exec; "
                            "only build-tool-declared provenance is available")
        rows.append({"ordinal": len(rows) + 1, "tool": tool,
            "tool_kind": "dexer" if tool in {"d8", "r8"} else "compiler",
            "evidence_kind": "build-tool-declared", "mapping": "gradle-init-script-task-record",
            "mapping_confidence": DECLARED_CONFIDENCE, "task_path": path, "task_type": row.get("task_type"),
            "parent_command_id": parent, "did_work": row.get("did_work"),
            "instrumentation": row.get("instrumentation", {}),
            "declared_arguments": _strings(declared.get("compiler_args")),
            "declared_settings": {name: declared.get(name) for name in (
                "release", "source_compatibility", "target_compatibility", "jvm_target", "module_name",
                "execution_strategy", "toolchain_home", "toolchain_java_version", "fork",
                "fork_executable", "input_file_count") if name in declared},
            "classpath_entry_count": len(_strings(declared.get("classpath"))),
            "inputs": inputs, "outputs": mapped(outputs), "observed_invocation_ordinals": matches})
    return rows, gaps
