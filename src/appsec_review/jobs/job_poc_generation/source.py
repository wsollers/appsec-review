"""The writer's answer, its textual checks, and the generated PoC source file.

The writer returns two function bodies and the headers they need; the application writes the file.
Nothing the model typed outside ``test_function`` and ``negative_control`` reaches the source, every
``#include`` line is generated here from a validated header name, and the function text may contain
no preprocessor syntax at all (a comment cannot hide a directive because ``#`` is rejected wherever
it appears). These are the checks that need no compiler; the AST checks live in :mod:`.policy`.
"""
from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
import re
from typing import Any, Protocol

from .policy import ENTRY_NAMES, Violation
from .settings import PocGenerationSettings
from .statuses import DECLINES

ANSWER_SCHEMA_NAME = "writer-answer"
NAME = re.compile(r"^poc_[a-z][a-z0-9_]{2,58}$")
_HEADER_NAME = re.compile(r"^[A-Za-z0-9_+.-]+(?:/[A-Za-z0-9_+.-]+)*$")
_PRAGMA = re.compile(r"\b(?:_Pragma|__pragma)\b")
_ASM = re.compile(r"\b(?:asm|_?_asm_?_?)\b")
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
BANNER = ("// Proof-of-concept unit-test functions generated by appsec-review (job_poc_generation).\n"
          "// This file is data for developers. It has no main, takes no input and is never run by the pipeline.\n")


class HeaderResolver(Protocol):
    def resolve(self, include: str) -> str | None:
        """The workspace-relative path of a project header, or ``None`` when no project header matches."""


@dataclass(frozen=True, slots=True)
class WriterAnswer:
    """A schema-valid answer of the writer; every field is untrusted model output."""

    test_name: str
    test_source: str
    includes: tuple[str, ...]
    control_name: str
    control_source: str
    setup: tuple[str, ...]
    expected_observation: str
    breakpoints: tuple[Mapping[str, Any], ...]
    notes: str

    @classmethod
    def from_result(cls, result: Mapping[str, Any]) -> "WriterAnswer":
        test, control = result["test_function"], result["negative_control"]
        return cls(str(test["name"]), str(test["source"]), tuple(str(item) for item in test["includes"]),
                   str(control["name"]), str(control["source"]), tuple(str(item) for item in result["setup"]),
                   str(result["expected_observation"]),
                   tuple({"function": str(item["function"]), "line": int(item["line"]), "why": str(item["why"])}
                         for item in result["breakpoints"]), str(result.get("notes", "")))

    @property
    def functions(self) -> tuple[str, str]:
        return (self.test_name, self.control_name)

    def record(self) -> dict[str, Any]:
        return {"test_function": {"name": self.test_name, "includes": list(self.includes),
                                  "source": self.test_source},
                "negative_control": {"name": self.control_name, "source": self.control_source},
                "setup": list(self.setup), "expected_observation": self.expected_observation,
                "breakpoints": [dict(item) for item in self.breakpoints], "notes": self.notes}


def decline_of(result: Mapping[str, Any]) -> tuple[str, str] | None:
    """The status and reason of a writer that declined, or ``None`` when it wrote functions."""
    decline = result.get("decline")
    if not isinstance(decline, Mapping):
        return None
    return str(decline["status"]), str(decline["why"])[:600]


def include_line(include: str, settings: PocGenerationSettings) -> str:
    return f"#include <{include}>" if include in settings.policy.allowed_std_headers else f'#include "{include}"'


def assemble(answer: WriterAnswer, settings: PocGenerationSettings, *, claim_id: str, package_id: str) -> str:
    """The text of the PoC file: a banner, the validated includes, then the two functions."""
    header = [f"// claim: {claim_id}", f"// review package: {package_id}"]
    lines = [BANNER.rstrip("\n"), *header, ""]
    lines += [include_line(item, settings) for item in answer.includes]
    return "\n".join([*lines, "", answer.test_source.strip("\n"), "", answer.control_source.strip("\n"), ""])


def check_answer(answer: WriterAnswer, settings: PocGenerationSettings, resolver: HeaderResolver | None
                 ) -> list[Violation]:
    """Violations that need no compiler: names, sizes, encoding, preprocessing and includes."""
    found: list[Violation] = []
    bounds = settings.bounds

    def add(rule: str, message: str, function: str | None = None) -> None:
        found.append(Violation(rule, message, None, function))

    names = answer.functions
    for name in names:
        if name in ENTRY_NAMES:
            add("entry_point", f"{name} is a program entry point", name)
        elif not NAME.match(name):
            add("name", f"a PoC function is named poc_<words> in lowercase; got {name[:80]!r}", name)
    if answer.test_name == answer.control_name:
        add("name", "the test function and the negative control need different names")
    for name, text in zip(names, (answer.test_source, answer.control_source), strict=True):
        lines = text.strip("\n").count("\n") + 1 if text.strip() else 0
        if not text.strip():
            add("size", f"{name} has no source", name)
        if lines > bounds.max_function_lines:
            add("size", f"{name} has {lines} lines; the bound is {bounds.max_function_lines}", name)
        if _CONTROL.search(text) or any(ord(character) > 126 for character in text):
            add("encoding", f"{name} contains a control or non-ASCII character", name)
        if "#" in text or "%:" in text or "??" in text:             # the directive, its digraph and its trigraph
            add("preprocessor", f"{name} contains preprocessor syntax; includes are listed, never written inline", name)
        if _PRAGMA.search(text):
            add("pragma", f"{name} uses a pragma operator", name)
        if _ASM.search(text):
            add("inline_asm", f"{name} uses an assembler keyword", name)
        if not re.search(rf"\b{re.escape(name)}\s*\(", text):
            add("missing_function", f"the source of {name} does not define a function of that name", name)
    seen: set[str] = set()
    if len(answer.includes) > bounds.max_includes:
        add("include", f"{len(answer.includes)} includes; the bound is {bounds.max_includes}")
    for include in answer.includes:
        if include in seen:
            add("include", f"{include} is listed twice")
        seen.add(include)
        if include in settings.policy.allowed_std_headers:
            continue
        if not _HEADER_NAME.match(include) or ".." in include.split("/") or len(include) > 128:
            add("include", f"{include[:80]!r} is not a plain relative header name")
        elif not any(include.endswith(suffix) for suffix in settings.policy.project_header_suffixes):
            add("include", f"{include} is neither an allowed standard header nor a project header name")
        elif resolver is None or resolver.resolve(include) is None:
            add("include", f"{include} is not a header of the project build that contains the sink")
    for label, items in (("setup", answer.setup), ("breakpoints", answer.breakpoints)):
        if len(items) > bounds.max_list_items:
            add("size", f"{label} has {len(items)} items; the bound is {bounds.max_list_items}")
    for text in (*answer.setup, answer.expected_observation, answer.notes,
                 *(f"{item['function']} {item['why']}" for item in answer.breakpoints)):
        if len(text) > bounds.max_text_chars:
            add("size", f"a prose field exceeds {bounds.max_text_chars} characters")
            break
    return found


def file_violations(text: str, settings: PocGenerationSettings) -> list[Violation]:
    if len(text.encode("utf-8")) > settings.bounds.max_file_bytes:
        return [Violation("size", f"the generated file exceeds {settings.bounds.max_file_bytes} bytes")]
    return []


def answer_errors(result: Any) -> list[str]:
    """Shape errors the closed schema does not express (decline status vocabulary)."""
    if isinstance(result, Mapping) and isinstance(result.get("decline"), Mapping):
        status = result["decline"].get("status")
        if status not in DECLINES:
            return [f"decline.status must be one of {list(DECLINES)}"]
    return []

