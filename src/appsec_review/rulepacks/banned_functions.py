"""Render the Semgrep/Opengrep rule file for the ``[banned_functions]`` table.

``rules/semgrep/banned-functions.yml`` is generated from ``appsec-review.toml`` and hash-locked in
``rules/semgrep/rules.lock.json`` like the other Semgrep rule files. Regenerate it after editing the
table::

    python -m appsec_review.rulepacks.banned_functions --write

``--check`` (also run by the test suite) fails when the file or its lock has drifted from the table.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import tomllib

from appsec_review.config.banned_functions import TIERS, BannedFunctions, parse_banned_functions

RULES = Path("rules") / "semgrep" / "banned-functions.yml"
LOCK = Path("rules") / "semgrep" / "rules.lock.json"
CONFIG = Path("appsec-review.toml")
RULE_PREFIX = "appsec-review.review-signal.sink.cpp-banned-function-"
_SEVERITY = {"high": "ERROR", "warning": "WARNING", "review": "INFO"}
_LIST = {"high": "microsoft-sdl-banned-h", "warning": "microsoft-sdl-banned-h", "review": "appsec-review-review-calls"}
_ADVICE = {
    "high": "it takes no destination size, has no bounds argument or has an unsafe contract",
    "warning": "it is bounded but easy to misuse, does not guarantee termination, or is a pedantic-level call",
    "review": "it is not banned, but its size, bounds, termination, null-check or format-string contract is a common defect site",
}


def render_rules(config: BannedFunctions) -> str:
    """The deterministic rule file text for ``config``; names are sorted so list order never matters."""

    lines = [
        "# Generated by `python -m appsec_review.rulepacks.banned_functions --write` from [banned_functions]",
        "# in appsec-review.toml. Do not edit by hand: change the table and regenerate.",
    ]
    if config.source:
        lines.append(f"# List source: {config.source}")
    lines.append("rules:")
    for tier in TIERS:
        names = sorted(config.names(tier))
        if not names:
            continue
        lines += [
            f"  - id: {RULE_PREFIX}{tier}",
            "    languages: [c, cpp]",
            "    message: >-",
            "      Call to $FUNC, a function on the banned-function list (" + tier + " tier): "
            + _ADVICE[tier] + ("." if tier == "review" else ". Prefer a bounded or checked alternative."),
            f"    severity: {_SEVERITY[tier]}",
            "    metadata:",
            "      list: " + _LIST[tier],
            f"      tier: {tier}",
            "    patterns:",
            "      - pattern: $FUNC(...)",
            "      - metavariable-regex:",
            "          metavariable: $FUNC",
            "          regex: '^(?:::|std::)?(?:" + "|".join(names) + ")$'",
        ]
    if lines[-1] == "rules:":
        lines[-1] = "rules: []"  # an empty table makes an empty, valid rule file
    return "\n".join(lines) + "\n"


def load_config(root: Path) -> BannedFunctions:
    document = tomllib.loads((root / CONFIG).read_text(encoding="utf-8"))
    return parse_banned_functions(document.get("banned_functions"))


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def expected_lock(root: Path) -> str:
    return _sha256(render_rules(load_config(root)))


def check(root: Path) -> list[str]:
    """Why the committed rule file or its lock no longer matches the table (empty when they do)."""

    problems = []
    expected = render_rules(load_config(root))
    path = root / RULES
    actual = path.read_text(encoding="utf-8") if path.is_file() else None
    if actual != expected:
        problems.append(f"{RULES} does not match [banned_functions]; run "
                        "`python -m appsec_review.rulepacks.banned_functions --write`")
    try:
        lock = json.loads((root / LOCK).read_text(encoding="utf-8"))
        recorded = lock["files"]["banned-functions.yml"]["sha256"]
    except (OSError, KeyError, ValueError):
        recorded = None
    if recorded != _sha256(expected):
        problems.append(f"{LOCK} does not record the hash of the generated {RULES.name}")
    return problems


def write(root: Path) -> None:
    text = render_rules(load_config(root))
    (root / RULES).write_text(text, encoding="utf-8")
    lock_path = root / LOCK
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    lock["files"]["banned-functions.yml"] = {"sha256": _sha256(text)}
    lock_path.write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=Path.cwd())
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the rule file and its lock entry")
    mode.add_argument("--check", action="store_true", help="fail when the committed file or lock drifted")
    args = parser.parse_args(argv)
    if args.write:
        write(args.root)
        print(f"wrote {RULES} and updated {LOCK.name}")
        return 0
    problems = check(args.root)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
