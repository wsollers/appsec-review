"""Generated views of the DFD and threat model (T-107): Mermaid diagrams and ``threat-model.md``.

The views are pure functions of the published JSON documents (the plain forms
``json.loads(contract.canonical(document))`` gives), so an output validator can re-render and
compare bytes. Nothing here is hand-edited, nothing carries a timestamp, everything is iterated in
id order, and every piece of target-derived text passes through ``sanitize_label`` (names) or, for
the sentences of the Markdown view, ``sanitize_text``: node ids and file names are built from
identities only. See docs/architecture/dfd-and-threat-model-generation.md
sections 6.5 and 9.
"""
from __future__ import annotations

import re
from typing import Any, Iterable, Mapping, Sequence

from appsec_review.threat_model import contract
from appsec_review.threat_model.contract import JOB_ID, Limits

MAX_LABEL_LENGTH = 80
SOURCE_HASH_PREFIX = "source-sha256: "
BANNER = (
    f"GENERATED by {JOB_ID} from run evidence.",
    "This is not the document of the target owner. It must not be hand-edited.",
    "Regenerate it from the published JSON documents of the run.",
)
OVERVIEW_FILE = "dfd.mmd"
MARKDOWN_FILE = "threat-model.md"
THREATS_ARE_QUESTIONS = (
    "These are questions raised by the evidence, not findings. A candidate threat says where a reviewer "
    "should look and what would have to be established; it does not say that a weakness exists."
)

MAX_TEXT_LENGTH = 300
_UNSAFE = re.compile(r"[^A-Za-z0-9 _./:#-]")
_UNSAFE_TEXT = re.compile(r"[^A-Za-z0-9 _./:#?,()-]")
_SPACE = re.compile(r"\s+")
_SHAPES = {"process": ('(("', '"))'), "data_store": ('[("', '")]'), "external_entity": ('["', '"]')}


def sanitize_label(text: str) -> str:
    """Target text as it may appear in a view: a closed character set, one line, at most 80 characters."""
    cleaned = _SPACE.sub(" ", _UNSAFE.sub(" ", text if isinstance(text, str) else "")).strip()
    return cleaned[:MAX_LABEL_LENGTH].strip() or "unnamed"


def sanitize_text(text: str, limit: int = MAX_TEXT_LENGTH) -> str:
    """A sentence as it may appear in the Markdown view: the label rule plus ``? , ( )``, at most ``limit``.

    For threat titles and questions, unknown statements and gap reasons, which are sentences and may
    embed a target name. Quotes, backticks, pipes, brackets and angle brackets are still removed.
    """
    cleaned = _SPACE.sub(" ", _UNSAFE_TEXT.sub(" ", text if isinstance(text, str) else "")).strip()
    return cleaned[:limit].strip() or "unnamed"


class _Prose(str):
    """A Markdown cell that is a sentence: rendered with ``sanitize_text`` instead of ``sanitize_label``."""


def node_id(identity: Any) -> str:
    """The Mermaid node id of an element or boundary id: ``proc:0123...`` becomes ``proc_0123...``."""
    return re.sub(r"[^A-Za-z0-9_]", "_", str(identity))


def process_file_name(process_id: Any) -> str:
    return f"dfd-{re.sub(r'[^A-Za-z0-9-]', '-', str(process_id))}.mmd"


def banner_lines(origin: Mapping[str, Any]) -> list[str]:
    """The generated banner with the run and target snapshot, without any comment or quote marker."""
    return [*BANNER, f"run: {sanitize_label(_text(origin.get('run_id')))}",
            f"target-snapshot: {sanitize_label(_text(origin.get('target_snapshot')))}"]


def source_hash_line(document: Any) -> str:
    return f"{SOURCE_HASH_PREFIX}{contract.canonical_sha256(document)}"


def _text(value: Any) -> str:
    return value if isinstance(value, str) else ""


def _records(document: Mapping[str, Any], key: str) -> list[Mapping[str, Any]]:
    found = [item for item in document.get(key) or () if isinstance(item, Mapping)]
    return sorted(found, key=lambda item: _text(item.get("id")))


def _origin(document: Mapping[str, Any]) -> Mapping[str, Any]:
    origin = document.get("origin")
    return origin if isinstance(origin, Mapping) else {}


# ---------------------------------------------------------------------------------------------
# Mermaid
# ---------------------------------------------------------------------------------------------

def _node(element: Mapping[str, Any]) -> str:
    opening, closing = _SHAPES.get(_text(element.get("kind")), _SHAPES["external_entity"])
    label = f"{sanitize_label(_text(element.get('name')))} ({sanitize_label(_text(element.get('basis')))})"
    return f"{node_id(element.get('id'))}{opening}{label}{closing}"


def _edge(flow: Mapping[str, Any]) -> str:
    suffix = sanitize_label(_text(flow.get("id")).split(":", 1)[-1][:8])
    label = f"{suffix} {sanitize_label(_text(flow.get('interaction')))} ({sanitize_label(_text(flow.get('basis')))})"
    return f'{node_id(flow.get("source"))} -->|"{label}"| {node_id(flow.get("target"))}'


def _diagram(dfd: Mapping[str, Any], view: str, shown: Sequence[Mapping[str, Any]],
             flows: Sequence[Mapping[str, Any]], notes: Sequence[str]) -> str:
    known = {_text(item.get("id")) for item in _records(dfd, "elements")}
    visible = {_text(item.get("id")) for item in shown}
    lines = [f"%% {line}" for line in banner_lines(_origin(dfd))]
    lines += [f"%% {source_hash_line(dfd)}", f"%% view: {view}", "flowchart LR"]

    placed: dict[str, str] = {}
    also: list[str] = []
    members: dict[str, list[str]] = {}
    boundaries = _records(dfd, "boundaries")
    for boundary in boundaries:
        boundary_id = _text(boundary.get("id"))
        for member in sorted({_text(item) for item in boundary.get("inside") or ()} & visible):
            if member in placed:
                also.append(f"%% {node_id(member)} is also inside {node_id(boundary_id)} "
                            f"({sanitize_label(_text(boundary.get('kind')))} boundary)")
            else:
                placed[member] = boundary_id
                members.setdefault(boundary_id, []).append(member)

    by_id = {_text(item.get("id")): item for item in shown}
    for boundary in boundaries:
        inside = members.get(_text(boundary.get("id")))
        if not inside:
            continue
        lines.append(f'  subgraph {node_id(boundary.get("id"))} '
                     f'["{sanitize_label(_text(boundary.get("kind")))} boundary"]')
        lines += [f"    {_node(by_id[member])}" for member in inside]
        lines.append("  end")
    lines += [f"  {_node(by_id[identity])}" for identity in sorted(visible - set(placed))]
    lines += [f"  {line}" for line in also]

    hidden = 0
    for flow in flows:
        source, target = _text(flow.get("source")), _text(flow.get("target"))
        if source not in known or target not in known:
            lines.append(f"  %% flow {sanitize_label(_text(flow.get('id')))} is not rendered: "
                         "an endpoint is not an element of the document")
        elif source in visible and target in visible:
            lines.append(f"  {_edge(flow)}")
        else:
            hidden += 1
    if hidden:
        lines.append(f"  %% {hidden} flows are not rendered: an endpoint is outside this view")
    lines += [f"  %% {note}" for note in notes]
    return "\n".join(lines) + "\n"


def render_mermaid(dfd: Mapping[str, Any], limits: Limits) -> tuple[dict[str, str], bool]:
    """File name to Mermaid text, and whether ``limits.max_render_nodes`` was reached.

    Within the bound there is one diagram, ``dfd.mmd``. Over it, ``dfd.mmd`` is an overview of the
    first ``max_render_nodes`` elements in id order and each process gets its own diagram of the
    process, the elements it has flows with, and those flows.
    """
    elements, flows = _records(dfd, "elements"), _records(dfd, "flows")
    bound = limits.max_render_nodes
    if len(elements) <= bound:
        return {OVERVIEW_FILE: _diagram(dfd, "complete", elements, flows, ())}, False

    omitted = len(elements) - bound
    views = {OVERVIEW_FILE: _diagram(
        dfd, "overview", elements[:bound], flows,
        (f"{omitted} elements are not rendered: max_render_nodes {bound} was reached",
         "each process has its own diagram: dfd-proc-ID.mmd"))}
    by_id = {_text(item.get("id")): item for item in elements}
    for process in elements:
        if process.get("kind") != "process":
            continue
        identity = _text(process.get("id"))
        touching = [flow for flow in flows if identity in (_text(flow.get("source")), _text(flow.get("target")))]
        peers = sorted({_text(flow.get(end)) for flow in touching for end in ("source", "target")} & set(by_id)
                       - {identity})
        kept = peers[:bound - 1]
        notes = ((f"{len(peers) - len(kept)} elements are not rendered: max_render_nodes {bound} was reached",)
                 if len(kept) < len(peers) else ())
        shown = sorted([process, *(by_id[peer] for peer in kept)], key=lambda item: _text(item.get("id")))
        views[process_file_name(identity)] = _diagram(dfd, f"process {sanitize_label(identity)}", shown, touching,
                                                      notes)
    return views, True


# ---------------------------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------------------------

def _cell(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (list, tuple)):
        return ", ".join(sanitize_label(_text(item)) for item in value) or "-"
    if isinstance(value, _Prose):
        return sanitize_text(value)
    return sanitize_label(_text(value))


def _locator(record: Mapping[str, Any]) -> str:
    """The first citation's source location: path and range, without the file digest."""
    for reference in record.get("evidence") or ():
        locator = reference.get("locator") if isinstance(reference, Mapping) else None
        if isinstance(locator, str) and locator:
            return sanitize_label(locator.rsplit("@", 1)[0])
    return "-"


def _table(headers: Sequence[str], rows: Iterable[Sequence[Any]]) -> list[str]:
    body = ["| " + " | ".join(_cell(item) for item in row) + " |"
            for row in rows]
    if not body:
        return ["None.", ""]
    return ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |", *body, ""]


def _threat_rows(threats: Iterable[Mapping[str, Any]]) -> list[list[Any]]:
    return [[item.get("id"), item.get("stride"), _Prose(_text(item.get("title"))), _Prose(_text(item.get("question"))),
             (item.get("mitigation") or {}).get("state") if isinstance(item.get("mitigation"), Mapping) else None,
             _locator(item)] for item in threats]


def render_markdown(dfd: Mapping[str, Any], threat_model: Mapping[str, Any], result: Mapping[str, Any]) -> str:
    """``threat-model.md``: the tables a person reads, from the three published documents."""
    origin, model_origin = _origin(dfd), _origin(threat_model)
    reference_data = {**(model_origin.get("reference_data") or {}), **(origin.get("reference_data") or {})}
    worker = origin.get("model") or model_origin.get("model")
    contributed = "no"
    if isinstance(worker, Mapping):
        contributed = f"yes ({sanitize_label(_text(worker.get('provider')))} {sanitize_label(_text(worker.get('model')))})"

    lines = ["# Generated threat model", ""]
    lines += [f"> {line}" for line in BANNER]
    lines += [">", *(f"> - {line}" for line in banner_lines(origin)[len(BANNER):]),
              f"> - dfd {source_hash_line(dfd)}", f"> - threat-model {source_hash_line(threat_model)}"]
    lines += [f"> - reference-data {sanitize_label(str(key))}: {sanitize_label(_text(reference_data[key]))}"
              for key in sorted(reference_data)]
    lines += [f"> - model worker contributed: {contributed}", ""]

    ledger = sorted((row for row in result.get("input_ledger") or () if isinstance(row, Mapping)),
                    key=lambda row: (_text(row.get("producer")), _text(row.get("output_kind"))))
    lines += ["## Input ledger", ""]
    lines += _table(("Producer", "Output kind", "State", "Coverage", "Upstream gaps", "Records read"),
                    ([row.get("producer"), row.get("output_kind"), row.get("state"), row.get("coverage_disposition"),
                      row.get("upstream_gap_count"), row.get("records_read")] for row in ledger))

    lines += ["## Elements", ""]
    lines += _table(("Id", "Kind", "Name", "Basis", "Citations", "First locator"),
                    ([item.get("id"), item.get("kind"), item.get("name"), item.get("basis"),
                      len(item.get("evidence") or ()), _locator(item)] for item in _records(dfd, "elements")))

    boundaries = _records(dfd, "boundaries")
    lines += ["## Trust boundaries", ""]
    lines += _table(("Id", "Kind", "Members"),
                    ([item.get("id"), item.get("kind"), sorted(_text(member) for member in item.get("inside") or ())]
                     for item in boundaries))

    lines += ["## Flows", ""]
    lines += _table(("Id", "Source", "Target", "Interaction", "Basis", "Crosses"),
                    ([item.get("id"), item.get("source"), item.get("target"), item.get("interaction"),
                      item.get("basis"), sorted(_text(crossed) for crossed in item.get("crosses") or ())]
                     for item in _records(dfd, "flows")))

    lines += ["## Entry points", ""]
    lines += _table(("Id", "Process", "Interaction", "Source class", "Enclosing symbol", "Basis", "First locator"),
                    ([item.get("id"), item.get("process"), item.get("interaction"), item.get("source_class"),
                      item.get("enclosing_symbol"), item.get("basis"), _locator(item)]
                     for item in _records(threat_model, "entry_points")))

    threats = _records(threat_model, "threats")
    headers = ("Id", "STRIDE", "Title", "Question", "Mitigation state", "First locator")
    kinds = {_text(item.get("id")): _text(item.get("kind")) for item in boundaries}
    lines += ["## Candidate threats", "", THREATS_ARE_QUESTIONS, ""]
    if not threats:
        lines += ["None.", ""]
    for boundary_id in sorted({_text(identity) for item in threats for identity in item.get("boundary_ids") or ()}):
        kind = f" ({sanitize_label(kinds[boundary_id])})" if boundary_id in kinds else ""
        lines += [f"### Boundary {sanitize_label(boundary_id)}{kind}", ""]
        lines += _table(headers, _threat_rows(item for item in threats
                                              if boundary_id in (item.get("boundary_ids") or ())))
    unbounded = [item for item in threats if not item.get("boundary_ids")]
    if unbounded:
        lines += ["### No boundary", ""]
        lines += _table(headers, _threat_rows(unbounded))

    unknowns = {_text(item.get("id")): item for item in (*_records(dfd, "unknowns"),
                                                         *_records(threat_model, "unknowns"))}
    lines += ["## Unknowns", ""]
    lines += _table(("Id", "Kind", "Statement", "Would resolve"),
                    ([item.get("id"), item.get("kind"), _Prose(_text(item.get("statement"))),
                      list(item.get("would_resolve") or ())]
                     for _, item in sorted(unknowns.items())))

    gaps = sorted((gap for gap in result.get("gaps") or () if isinstance(gap, Mapping)),
                  key=lambda gap: (_text(gap.get("code")), _text(gap.get("scope_id")), _text(gap.get("reason")),
                                   _text(gap.get("gap_id"))))
    lines += ["## Gaps", ""]
    lines += _table(("Code", "Scope", "Reason", "Retryable"),
                    ([gap.get("code"), gap.get("scope_id"), _Prose(_text(gap.get("reason"))), bool(gap.get("retryable"))]
                     for gap in gaps))
    return "\n".join(lines).rstrip("\n") + "\n"
