"""Check the synthetic Grype stdout contract against the pinned executable.

The unit tier loads no recorded tool-output files: Grype stdout and the cve-bin-tool SQLite
tables are generated by Python doubles. Never attach fabricated tool provenance to those doubles.
This real version observation writes its receipt beside the run-owned output; the database
boundary tests cover the remaining assumptions when their declared prerequisites are available.
"""
from __future__ import annotations

import json

from appsec_review.container_runtime import ExecutionRequest
from appsec_review.storage import atomic_json, file_sha256
from tests.fixtures.grype import Docker

from .support import ROOT, work_path


def test_pinned_grype_version_matches_unit_double(grype_executor):
    executor = grype_executor
    tool = executor.catalog.tool("tool-grype")
    source = executor.run_root / "input"
    source.mkdir()
    result = executor.execute(ExecutionRequest(
        tool.tool_id, (tool.executable, "version", "-o", "json"), source,
        work_path(executor.run_root, "grype_db_sync.import") / "version",
    ))
    assert result.exit_code == 0 and not result.timed_out
    output = executor.run_root / result.stdout_path
    actual = json.loads(output.read_bytes())
    assert actual["application"] == "grype"
    assert actual["version"] == Docker().version == tool.version
    atomic_json(output.with_name(output.name + ".provenance.json"), {
        "tool_id": tool.tool_id, "image_id": result.image_id, "tool_version": actual["version"],
        "input_sha256": result.argv_identity, "output_sha256": file_sha256(output),
        "unit_double_sha256": file_sha256(ROOT / "tests/fixtures/grype.py"),
    })
