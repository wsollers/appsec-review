def pytest_runtest_setup(item: pytest.Item) -> None:
    if os.environ.get(GATE) != "1":
        pytest.skip(f"signing acceptance tests run only with {GATE}=1")


def signing_config(path: Path, *, trusted_keys_dir: Path, image_signatures_dir: Path) -> Path:
    """Write the repository configuration with only its ``[signing]`` values replaced."""
    text = CONFIG_SOURCE.read_text(encoding="utf-8")
    start = text.index("\n[signing]\n")
    end = text.index("\n[", start + 1)
    section = text[start:end]
    for key, value in (("openssl", OPENSSL_BINARY), ("trusted_keys_dir", str(trusted_keys_dir)),
                       ("image_signatures_dir", str(image_signatures_dir)), ("image_enforcement", "required")):
        line = f"{key} = {json.dumps(value)}"
        section, count = re.subn(rf"^{key} = .*$", lambda _match: line, section, flags=re.MULTILINE)
        assert count == 1, f"[signing].{key} not found exactly once in {CONFIG_SOURCE}"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text[:start] + section + text[end:], encoding="utf-8")
    return path


@dataclass
class Operator:
    """An operator's host: a configuration, key paths and the ``appsec-review`` command."""

    root: Path
    config: Path
    private_key: Path
    trusted_keys_dir: Path
    image_signatures_dir: Path
    environment: dict[str, str]

    def command(self) -> list[str]:
        script = Path(sys.executable).with_name("appsec-review")
        return [str(script)] if os.access(script, os.X_OK) else [sys.executable, "-m", "appsec_review"]

    def run(self, *argv: str, environment: dict[str, str] | None = None,
            timeout: float = 300) -> subprocess.CompletedProcess[str]:
        return subprocess.run(argv, cwd=self.root, env=self.environment if environment is None else environment,
                              stdin=subprocess.DEVNULL, capture_output=True, text=True, check=False,
                              timeout=timeout)

    def signing(self, *argv: str) -> tuple[int, dict]:
        """Run ``appsec-review --config <config> signing ...`` and return its exit code and JSON report."""
        completed = self.run(*self.command(), "--config", str(self.config), "signing", *argv)
        try:
            report = json.loads(completed.stdout)
        except ValueError:
            pytest.fail(f"signing {argv[0]} printed no JSON report (exit {completed.returncode}): "
                        f"{completed.stdout[-500:]}{completed.stderr[-2000:]}")
        return completed.returncode, report


@pytest.fixture
def operator(tmp_path, openssl) -> Operator:
    scratch = tmp_path / "child-tmp"
    scratch.mkdir()
    environment = {name: value for name, value in os.environ.items() if name not in _AMBIENT}
    environment["TMPDIR"] = str(scratch)
    signatures = tmp_path / "image-signatures"
    trusted = tmp_path / "trusted"
    config = signing_config(tmp_path / "config" / "appsec-review.toml", trusted_keys_dir=trusted,
                            image_signatures_dir=signatures)
    return Operator(tmp_path, config, tmp_path / "private" / "op.pem", trusted, signatures, environment)


