        self.assertEqual(published["job_id"], census_mod.JOB)
        self.assertEqual({row["path"]: row["class"] for row in published["files"]},
                         {"src/hello.c": "program:c", "logo.png": "binary_media", "fix-build.patch": "patch_diff",
                          "config.guess": "build_system", "README": "documentation"})
        self.assertEqual(census_mod.validate(RUN_ID), attempt)
        (self.target / "new.kt").write_text("fun x() {}\n")
        with self.assertRaises(state.Blocked):
            census_mod.validate(RUN_ID)


