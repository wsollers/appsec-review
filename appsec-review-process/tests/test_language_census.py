def write(root: Path, files: dict[str, bytes | str]) -> Path:
    for path, data in files.items():
        target = root.joinpath(*path.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data.encode("utf-8") if isinstance(data, str) else data)
    return root


def census(root: Path, **kwargs) -> dict:
    body = census_mod.census(root, RULES, CATALOG, **kwargs)
    return census_mod.document(body, run_id=RUN_ID, source_snapshot_sha256="sha256:" + HEX,
                               source_tree_sha256="sha256:" + HEX, rules_sha256=HEX)


class FakeNode:
    """A tree-sitter root with no children: enough for summarize_tree to walk."""
    is_error = is_missing = False
    is_named, type, children = True, "program", []

    def walk(self):
        node = self
        return types.SimpleNamespace(node=node, goto_first_child=lambda: False, goto_next_sibling=lambda: False,
                                     goto_parent=lambda: False)


class FakeParser:
    parsed: list[tuple[str, bytes]] = []

    def __init__(self, language):
        self.language = language

    def parse(self, data):
        FakeParser.parsed.append((self.language, data))
        return types.SimpleNamespace(root_node=FakeNode())


FAKE_TREE_SITTER = types.SimpleNamespace(Language=lambda value: value, Parser=FakeParser)


def scan(root: Path) -> treesitter_ast.Scan:
    FakeParser.parsed = []
    with patch.object(treesitter_ast, "load_languages",
                      return_value=({name: name for name in ("bash", "c", "python")}, {}, [])):
        result = treesitter_ast.Scan(root, tree_sitter=FAKE_TREE_SITTER, label="fixture")
        result.files = list(result.records())
    return result


